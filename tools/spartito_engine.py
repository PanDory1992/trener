"""Builds web/js/spartito/engine.js: the notation engine of Miki's Spartito as an ES module.

The engine is Miki's own code and stays OFF git (decision 15.11.2026): the source
copy (spartito-src/spartito.js) and the module this makes are both in .gitignore.
Without them Trener runs as before and the Nuty mode says the engine is missing.

What is taken: the sections 00_core .. 55_export of spartito.js, word for word
(model, notation, glyphs, layout, display list, exports). Not taken: 60_live,
65_brain, 70_ui (Live, the device's brain and its editor window).

Usage (in the trener folder):
    python3 tools/spartito_engine.py [path/to/spartito.js]
default source: spartito-src/spartito.js; on the PC also B:/Spartito/spartito.js.
"""
import hashlib
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "web" / "js" / "spartito" / "engine.js"
FIRST, STOP = "// ---- src/00_core.js", "// ---- src/60_live.js"


def source(arg):
    for p in ([pathlib.Path(arg)] if arg else []) + [ROOT / "spartito-src" / "spartito.js", pathlib.Path("B:/Spartito/spartito.js")]:
        if p.is_file():
            return p
    sys.exit("spartito_engine.py: no spartito.js (spartito-src/spartito.js or a path)")


def main():
    src = source(sys.argv[1] if len(sys.argv) > 1 else None)
    text = src.read_text(encoding="utf-8")
    a, b = text.find(FIRST), text.find(STOP)
    if a < 0 or b < a:
        sys.exit(f"spartito_engine.py: sections 00..55 not found in {src}")
    body = text[a:b]
    names = re.findall(r"^function (\w+)\s*\(", body, re.M)
    for line in re.findall(r"^var (.+)$", body, re.M):
        names += re.findall(r"(?:^|,\s*)(\w+)\s*=", line)
    names = sorted(set(names))
    md5 = hashlib.md5(body.encode("utf-8")).hexdigest()
    head = (f"// GENERATED by tools/spartito_engine.py from {src.name} (sections 00_core..55_export), md5 {md5}.\n"
            "// Miki's Spartito engine, unchanged. Not in git. Do not edit: run the tool again.\n")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(head + body + "\nexport {\n  " + ",\n  ".join(names) + "\n};\nexport const ENGINE_MD5 = '" + md5 + "';\n", encoding="utf-8")
    print(f"{OUT.relative_to(ROOT)}: {len(names)} names, md5 {md5}")


if __name__ == "__main__":
    main()
